/* 무드별 조형 규칙 — MOOD_DESIGN_RULES 가이드 적용.
   무드를 감성 형용사가 아니라 "실제 디자인 결정의 집합"으로 내려준다.

   form / type 을 나눠 둔 이유:
   심볼형·조합형 프롬프트에는 "글자·텍스트 없이" 라는 지시가 들어가는데,
   같은 프롬프트에 자간·워드마크 지시가 섞이면 모델이 글자를 그려 넣는다.
   그래서 type(타이포그래피)은 글자가 들어가는 형태에만 붙인다. */

/* palette 를 form 에서 떼어낸 이유:
   사용자가 브랜드 컬러를 직접 고르면 무드의 권장 팔레트와 정면으로 충돌한다
   (예: 럭셔리 + 핑크 → "블랙·아이보리…" 와 "핑크" 가 한 프롬프트에).
   색을 고른 경우엔 palette 를 빼고 고른 색만 내려보낸다. */
const rule = (form, type, palette = "") => ({
  form: form.trim(),
  type: type.trim(),
  palette: palette.trim(),
});

